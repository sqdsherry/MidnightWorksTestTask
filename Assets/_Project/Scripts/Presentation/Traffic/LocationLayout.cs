        private string _locationId = string.Empty;

        [SerializeField, FormerlySerializedAs("_parkingExit"), FormerlySerializedAs("_barrier")]
        [Tooltip("Parking entrance barrier reached from the road (Service Type of kind Barrier).")]
        private ServicePointView _mainEntrance;

        [SerializeField]
        [Tooltip("Parking entrance barrier reached after a service (Service Type of kind Barrier).")]
        private ServicePointView _serviceEntrance;

        [SerializeField]
        [Tooltip("Service points of the location (wash...), built or not, each with the same number of Buffer Slots. Not the entrances.")]
        private ServicePointView[] _servicePoints = new ServicePointView[0];

        [SerializeField]
        [Tooltip("Road node where cars appear; its forward is their initial heading.")]
        private RoadNode _spawnNode;

        [SerializeField]
        [Tooltip("Road node where leaving cars drive to and disappear.")]
        private RoadNode _exitNode;

        [SerializeField]
        [Tooltip("Entry queue lane slots (road nodes); element 0 is the head at the fork.")]
        private RoadNode[] _queueSlots = new RoadNode[0];

        [SerializeField]
        [Tooltip("Parking slots (road nodes); forward = the direction a parked car faces. Includes slots still to be bought.")]
        private RoadNode[] _parkingSlots = new RoadNode[0];

        [SerializeField]
        [Tooltip("Build plots of the location: bays and parking slots that are bought later.")]
        private BuildPlotView[] _buildPlots = new BuildPlotView[0];

        [Header("Staff & Supplies")]
        [SerializeField]
        [Tooltip("The location's warehouse (boxes are bought here).")]
        private WarehouseView _warehouse;

        [SerializeField]
        [Tooltip("Blue pad of the warehouse (Target = Warehouse): hires the storekeeper.")]
        private ManagePadView _warehousePad;

        [SerializeField]
        [Tooltip("Door of the staff room: hired NPCs appear here, facing its forward.")]
        private Transform _staffRoom;

        [SerializeField]
        [Tooltip("Blue manage pads, exactly one per point (both entrances and every service point, built or not).")]
        private ManagePadView[] _managePads = new ManagePadView[0];

        private readonly List<TrafficZone> _zones = new List<TrafficZone>();

        private RoadNode[] _nodes;
        private RouteGraph _graph;
        private string _graphProblem;
        private RoadNode _mainEntranceNode;
        private RoadNode _serviceEntranceNode;
        private RoadNode[] _servicePointNodes;

