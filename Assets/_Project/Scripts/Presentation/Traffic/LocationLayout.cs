    /// <summary>
    /// Scene markup of one location: its points (two parking entrances and the service points with their buffers),
    /// its one-way road graph (<see cref="RoadNode"/>s below this object), spawn/exit nodes, entry queue slots and parking
    /// slots. Resolves engine-agnostic <see cref="CarDestination"/>s into road nodes and builds the <see cref="RouteGraph"/>
    /// cars drive on.
    /// </summary>
    /// <remarks>
    /// Every point's Car Spot carries a <see cref="RoadNode"/>, so a point is just another node of the graph.
    /// <para><b>Build plots.</b> <see cref="ServicePoints"/> and the parking slots list EVERYTHING the location can have,
    /// built or not; a <see cref="BuildPlotView"/> covers what is not built yet. A point is built at the start when it is
    /// not inside any plot's Target; the lot starts with the slots no plot covers (the covered ones are the last slots).</para>
    /// <para><b>Staff and supplies.</b> One warehouse with its blue pad, the staff room where hired NPCs appear, and one blue
    /// manage pad per point (both entrances included).</para>
    /// Whitebox layout v3.1 is generated by <c>AutoService → Whitebox → Build Location 1 Roads</c> (GDD §3).
    /// </remarks>
    public sealed class LocationLayout : MonoBehaviour
    {
        private const float SlotGizmoRadius = 0.6f;

